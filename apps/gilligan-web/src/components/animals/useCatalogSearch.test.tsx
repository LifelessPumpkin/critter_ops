import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { useCatalogSearch } from "./useCatalogSearch";
import type { CatalogPage } from "@/lib/api/animalCatalog";
const page = (items: number[], hasMore = false): CatalogPage<number> => ({ items, page: 1, pageSize: 25, hasMore });
afterEach(() => { cleanup(); vi.useRealTimers(); });
it("debounces immediately invalidated queries, aborts old requests and rejects out-of-order completions", async () => {
  vi.useFakeTimers();
  const resolves: ((page: CatalogPage<number>) => void)[] = [];
  const fetchPage = vi.fn((_page: number, _signal: AbortSignal) => new Promise<CatalogPage<number>>(resolve => resolves.push(resolve)));
  const { result, rerender, unmount } = renderHook(({ key }) => useCatalogSearch(key, key, true, fetchPage, "Failed"), { initialProps: { key: "python" } });
  await act(async () => { vi.advanceTimersByTime(299); });
  expect(fetchPage).not.toHaveBeenCalled();
  await act(async () => { vi.advanceTimersByTime(1); });
  const first = fetchPage.mock.calls[0][1];
  rerender({ key: "royal" });
  expect(first.aborted).toBe(true);
  expect(result.current.items).toEqual([]);
  await act(async () => { vi.advanceTimersByTime(300); });
  await act(async () => resolves[1](page([2])));
  await act(async () => resolves[0](page([1])));
  expect(result.current.items).toEqual([2]);
  expect(result.current.loading).toBe(false);
  unmount();
  expect(fetchPage.mock.calls[1][1].aborted).toBe(true);
});
it("keeps one bounded page, resets on category/species/term change, and cancels on close", async () => {
  vi.useFakeTimers();
  const fetchPage = vi.fn(async (n: number, _signal: AbortSignal) => page([n], true));
  const { result, rerender } = renderHook(({ key, enabled }) => useCatalogSearch(key, "", enabled, fetchPage, "Failed"), { initialProps: { key: "species:1", enabled: true } });
  await act(async () => { vi.runOnlyPendingTimers(); });
  expect(result.current.items).toEqual([1]);
  act(() => result.current.next());
  await act(async () => { vi.runOnlyPendingTimers(); });
  expect(result.current.items).toEqual([2]);
  expect(result.current.page).toBe(2);
  rerender({ key: "species:2", enabled: true });
  expect(result.current.items).toEqual([]);
  expect(result.current.page).toBe(1);
  await act(async () => { vi.runOnlyPendingTimers(); });
  rerender({ key: "species:2", enabled: false });
  expect(fetchPage.mock.calls.at(-1)![1].aborted).toBe(true);
  expect(result.current.loading).toBe(false);
});
it("reports failures, retries, and exposes empty results", async () => {
  vi.useFakeTimers();
  const fetchPage = vi.fn().mockRejectedValueOnce(new Error("offline")).mockResolvedValue(page([]));
  const { result } = renderHook(() => useCatalogSearch("", "", true, fetchPage, "Unable to load species. Please try again."));
  await act(async () => { vi.runOnlyPendingTimers(); });
  expect(result.current.error).toMatch(/Unable/);
  act(() => result.current.retry());
  await act(async () => { vi.runOnlyPendingTimers(); });
  expect(result.current.error).toBe("");
  expect(result.current.items).toEqual([]);
  expect(result.current.hasMore).toBe(false);
});
